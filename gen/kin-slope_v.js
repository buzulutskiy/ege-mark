function verb(body, stem) { return stem + (body.was === "было" ? "ось" : body.was === "была" ? "ась" : "ся"); }
/* кто движется: человек — только если скорость правдоподобная (до 12 м/с), иначе тело или автомобиль */
function actor(rnd, vmax) { return (vmax <= 12 && rnd.chance(0.5)) ? rnd.pick(RUNNERS) : rnd.pick(BODIES); }
function toNum(a) { return parseFloat(String(a).replace(/−/g, "-").replace(",", ".")); }
/* «красивое» ли число: не длиннее одного знака после запятой и не ноль */
function nice(v) { return v !== 0 && Math.abs(Math.round(v * 10) - v * 10) < 1e-9 && Math.abs(v) >= 0.5 && Math.abs(v) <= 60; }

/* границы вертикальной оси под реально нарисованную линию: без пустых клеток снизу и сверху */
function fitY(pts, yStep) {
  const ys = pts.map(p => p[1]);
  const lo = Math.min(...ys), hi = Math.max(...ys);
  return { yFrom: lo >= 0 ? 0 : lo - yStep, yTo: hi + yStep };
}

/* ломаная: делим 0..T на куски по сетке, среди них — тот, про который спрашивают */
function brokenLine(rnd, T, xStep, yFrom, yTo, yStep) {
  const cellsX = T / xStep;
  const nSeg = rnd.pick([3, 4]);
  const cuts = rnd.shuffle(Array.from({ length: cellsX - 1 }, (_, i) => (i + 1) * xStep))
    .slice(0, nSeg - 1).sort((a, b) => a - b);
  const ts = [0, ...cuts, T];
  const ys = ts.map(() => yFrom + rnd.int(0, (yTo - yFrom) / yStep) * yStep);
  return ts.map((t, i) => [t, ys[i]]);
}

