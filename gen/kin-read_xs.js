/* глагол в прошедшем времени под род тела: verb(body, "сдвинул") → «сдвинулось»/«сдвинулась»/«сдвинулся» */
function verb(body, stem) {
  return stem + (body.was === "было" ? "ось" : body.was === "была" ? "ась" : "ся");
}
/* «ехало»/«ехала»/«ехал» — для глаголов без -ся */
function verbP(body, stem) {
  return stem + (body.was === "было" ? "о" : body.was === "была" ? "а" : "");
}
/* ответ строкой → число (типографский минус и запятая) */
function toNum(a) { return parseFloat(String(a).replace(/−/g, "-").replace(",", ".")); }


/* границы вертикальной оси под реально нарисованную линию */
function fitY(pts, yStep) {
  const ys = pts.map(p => p[1]);
  const lo = Math.min(...ys), hi = Math.max(...ys);
  return { yFrom: lo >= 0 ? 0 : lo - yStep, yTo: hi + yStep };
}

