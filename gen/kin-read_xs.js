/* global RND, GRAPH */
/* Приём «Путь и перемещение по графику координаты».
   Образец модуля-генератора: вид signed написан полностью, остальные виды — по нему. */
const { fmtNum, fmtAns, fmtSigned, fmtPar, plural, pluralWord } = RND;

/* n — именительный, g — родительный, mov — причастие в родительном («движущегося»/«движущейся»),
   it — местоимение («оно»/«она»/«он»), was — «было»/«была»/«был» */
const BODIES = [
  { n: "тело", g: "тела", mov: "движущегося", it: "оно", was: "было" },
  { n: "материальная точка", g: "материальной точки", mov: "движущейся", it: "она", was: "была" },
  { n: "электрокар", g: "электрокара", mov: "движущегося", it: "он", was: "был" },
  { n: "автомобиль", g: "автомобиля", mov: "движущегося", it: "он", was: "был" },
];

const GEN = {
  key: "read_xs",
  title: "Путь и перемещение по графику координаты",
  kinds: [
    {
      id: "signed",
      title: "Перемещение со знаком",
      like: ["sd969870", "sd930022"],
      make(rnd) {
        /* сетка: время 0..T, координата — клетки по yStep, могут быть отрицательные */
        const T = rnd.pick([8, 10, 12, 14]);
        const yStep = rnd.pick([2, 5, 10]);
        const negative = rnd.chance(0.55);
        const yFrom = negative ? -3 * yStep : 0, yTo = negative ? 3 * yStep : 6 * yStep;
        const cellsY = (yTo - yFrom) / yStep;

        /* ломаная из 3–4 отрезков, все узлы на сетке (моменты — кратны шагу по времени);
           старт и финиш не совпадают */
        const xStep = T <= 10 ? 1 : 2;
        const cellsX = T / xStep;
        const nSeg = rnd.pick([3, 4]);
        const cuts = rnd.shuffle(Array.from({ length: cellsX - 1 }, (_, i) => (i + 1) * xStep)).slice(0, nSeg - 1).sort((a, b) => a - b);
        const ts = [0, ...cuts, T];
        let ys;
        do {
          ys = [];
          for (let i = 0; i <= nSeg; i++) ys.push(yFrom + rnd.int(0, cellsY) * yStep);
        } while (ys[0] === ys[ys.length - 1] || ys.some((y, i) => i && y === ys[i - 1] && i < ys.length - 1 && ys[i + 1] === y));
        const pts = ts.map((t, i) => [t, ys[i]]);

        const x0 = ys[0], x1 = ys[ys.length - 1];
        const s = x1 - x0;
        const body = rnd.pick(BODIES);
        const graph = {
          x: { label: "t, с", from: 0, to: T, step: xStep, tick: xStep },
          y: { label: "x, м", from: yFrom, to: yTo, step: yStep, tick: yStep },
          lines: [{ pts }],
        };
        const dir = s > 0 ? "вправо" : "влево";
        const plain = `На рисунке представлен график зависимости координаты x ${body.g}, ${body.mov} прямолинейно вдоль оси Ox, от времени t. Определите проекцию перемещения ${body.g} на ось Ox в промежутке времени от 0 до ${T} с. Ответ запишите в метрах с учётом знака проекции.`;
        return {
          plain, svg: GRAPH.plot(graph), table: null,
          answer: fmtAns(s), unit: "м",
          simple: `Спрашивают не путь, а на сколько ${body.n} ${body.was === "было" ? "сдвинулось" : body.was === "была" ? "сдвинулась" : "сдвинулся"} за ${plural(T, "секунду", "секунды", "секунд")} и в какую сторону. Смотришь, где ${body.it} ${body.was} в начале, где в конце, и вычитаешь.`,
          raz: {
            dano: [
              `На картинке график. Внизу — время t в секундах. Слева — число x в метрах: где ${body.n} стоит на прямой. Это число называют координатой.`,
              `Нужен кусок от 0 до ${T} секунд. Значит, с графика надо взять всего две точки: где ${body.n} ${body.was} в самом начале и где — на ${T}-й секунде.`,
              `Как взять точку: находишь на нижней оси нужную секунду, ведёшь пальцем вверх до линии, потом влево до оси x и читаешь число. В начале это ${fmtSigned(x0)}, на ${T}-й секунде ${fmtSigned(x1)}.`,
              negative ? "Минус здесь значит просто «слева от нуля». Ничего страшного." : "Линия между этими точками ломается — но для перемещения важны только начало и конец.",
              `Найти надо: на сколько ${body.it} ${body.was === "было" ? "сдвинулось" : body.was === "была" ? "сдвинулась" : "сдвинулся"} за эти ${T} секунд и в какую сторону. Ответ со знаком.`,
            ],
            plan: [
              "Берём с графика число в начале.",
              "Берём число в конце.",
              "Из конца вычитаем начало. Это и есть ответ.",
            ],
            steps: [
              { t: "Что такое перемещение",
                p: ["Перемещение — это на сколько тело сдвинулось от старта. Не сколько проехало всего, а от точки старта до точки финиша.",
                    "Сдвинулось вправо — ответ с плюсом. Влево — с минусом. Слово «проекция» в задании как раз про этот знак."] },
              { t: "Формула",
                p: ["f: s_x = x − x_0",
                    "Читается так: сдвиг = где стал минус где был.",
                    "x — число в конце. x_0 — число в начале. Маленький ноль внизу всегда значит «в начале»."] },
              { t: "Подставляем числа",
                p: [`В конце ${body.n} ${body.was} в точке ${fmtSigned(x1)}, в начале — в точке ${fmtSigned(x0)}.`,
                    `f: s_x = ${fmtSigned(x1)} − ${fmtPar(x0)}`,
                    ...(x0 < 0 ? ["Минус перед скобкой и минус внутри дают плюс:", `f: s_x = ${fmtSigned(x1)} + ${fmtNum(-x0)} = ${fmtSigned(s)}`]
                               : [`f: s_x = ${fmtSigned(s)}`])] },
              { t: "Что получилось",
                p: [`${s > 0 ? "Плюс" : "Минус"} ${fmtNum(Math.abs(s))}. ${body.n[0].toUpperCase() + body.n.slice(1)} ${body.was === "было" ? "сдвинулось" : body.was === "была" ? "сдвинулась" : "сдвинулся"} на ${plural(Math.abs(s), "метр", "метра", "метров")} ${dir}.`,
                    `Проверь по графику: было ${fmtSigned(x0)}, стало ${fmtSigned(x1)}. Число ${s > 0 ? "выросло — значит, правда сдвинулось вправо" : "уменьшилось — значит, правда сдвинулось влево"}.`] },
            ],
            ans: `${fmtSigned(s)} (метров, со знаком ${s > 0 ? "плюс" : "минус"})`,
            err: `Часто вычитают наоборот: ${fmtSigned(x0)} − ${fmtPar(x1)} = ${fmtSigned(-s)}. Порядок один: из конца вычитаем начало. Ещё путают с путём и начинают складывать все куски — тут этого не надо.`,
          },
          dbg: { graph, vars: { T, pts, x0, x1, s } },
        };
      },
    },
  ],
};

if (typeof module !== "undefined" && module.exports) module.exports = GEN;
if (typeof window !== "undefined") (window.GEN = window.GEN || {})["fiz:" + GEN.key] = GEN;
