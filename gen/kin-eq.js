const { fmtNum, fmtAns, fmtSigned, fmtPar, plural, pluralWord } = RND;

function toNum(a) { return parseFloat(String(a).replace(/−/g, "-").replace(",", ".")); }
function nice(v) { return Math.abs(Math.round(v * 10) - v * 10) < 1e-9; }

/* «2 + t − t²» — уравнение движения из чисел, с правильными знаками и без единиц-коэффициентов */
function poly(x0, v0, c) {
  let s = fmtNum(x0);
  if (v0 !== 0) s += (v0 > 0 ? " + " : " − ") + (Math.abs(v0) === 1 ? "" : fmtNum(Math.abs(v0))) + "t";
  if (c !== 0) s += (c > 0 ? " + " : " − ") + (Math.abs(c) === 1 ? "" : fmtNum(Math.abs(c))) + "t²";
  return s;
}
const COEF = c => Math.abs(c) === 1 ? (c > 0 ? "1" : "−1") : fmtSigned(c);

