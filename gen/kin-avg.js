/* Приём «Средняя скорость». */
const { fmtNum, fmtAns, fmtSigned, fmtPar, plural, pluralWord } = RND;

function toNum(a) { return parseFloat(String(a).replace(/−/g, "-").replace(",", ".")); }
function nice(v) { return Math.abs(Math.round(v * 10) - v * 10) < 1e-9; }
function fitY(pts, yStep) {
  const ys = pts.map(p => p[1]);
  return { yFrom: Math.min(...ys) >= 0 ? 0 : Math.min(...ys) - yStep, yTo: Math.max(...ys) + yStep };
}
/* площадь под ломаной от 0 до T (линия не уходит под ось) */
function area(pts) {
  let s = 0;
  for (let i = 1; i < pts.length; i++) s += (pts[i - 1][1] + pts[i][1]) / 2 * (pts[i][0] - pts[i - 1][0]);
  return s;
}

