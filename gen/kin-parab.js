/* global RND, GRAPH */
/* Приём «Разгон из покоя: парабола и таблица». */
const { fmtNum, fmtAns, fmtSigned, fmtPar, plural, pluralWord } = RND;

function toNum(a) { return parseFloat(String(a).replace(/−/g, "-").replace(",", ".")); }
function nice(v) { return Math.abs(Math.round(v * 10) - v * 10) < 1e-9; }

const GEN = {
  key: "parab",
  title: "Разгон из покоя: парабола и таблица",
  kinds: [
    {
      id: "table",
      title: "Ускорение по таблице",
      check: t => {
        const v = t.dbg.vars;
        /* пересчитываем по каждой строке таблицы, кроме первой: все должны дать одно ускорение */
        const accs = v.rows.slice(1).map(r => 2 * (r[1] - v.x0) / (r[0] * r[0]));
        if (accs.some(x => Math.abs(x - accs[0]) > 1e-9)) return `строки таблицы дают разные ускорения: ${accs.join(", ")}`;
        return Math.abs(accs[0] - toNum(t.answer)) < 1e-9 ? null : `по таблице ускорение ${accs[0]}, а в ответе ${t.answer}`;
      },
      make(rnd) {
        /* x = x0 + a·t²/2; подбираем так, чтобы все клетки таблицы были «красивыми» */
        const a = rnd.pick([0.5, 1, 1.5, 2, 3, 4]);
        const x0 = rnd.pick([0, 2, 3, 5]);
        /* берём только те моменты, при которых координата выходит круглой */
        const okTs = [2, 3, 4, 5, 6].filter(tt => nice(a * tt * tt / 2));
        const ts = rnd.shuffle(okTs).slice(0, 2).sort((p, q) => p - q);
        const rows = [[0, x0], ...ts.map(tt => [tt, x0 + a * tt * tt / 2])];
        const use = rows[rows.length - 1];                 /* по какой строке считаем */
        const dx = use[1] - x0;
        return {
          plain: `Точечное тело начинает движение из состояния покоя и движется равноускоренно вдоль оси Ox по гладкой горизонтальной поверхности. Используя таблицу, определите значение проекции на ось Ox ускорения этого тела. Ответ дайте в метрах на секунду в квадрате.`,
          svg: null,
          table: GRAPH.table(["t, с", "x, м"], rows),
          answer: fmtAns(a), unit: "м/с²",
          simple: `Вместо графика таблица. Принцип тот же: берёшь любую строку кроме первой и подставляешь в формулу разгона из покоя. Только не забудь вычесть стартовую координату ${fmtNum(x0)}.`,
          raz: {
            dano: [
              `Вместо графика таблица. В ней ${plural(rows.length, "строка", "строки", "строк")}: ${rows.map(r => `при t = ${fmtNum(r[0])} координата ${fmtNum(r[1])}`).join("; ")} (метры).`,
              "Сказано: тело стартует из состояния покоя, значит, начальная скорость v_0 = 0.",
              "Найти надо ускорение a_x в м/с².",
            ],
            plan: [
              "Из первой строки берём стартовую координату.",
              "Берём любую другую строку и считаем, на сколько тело сдвинулось.",
              "Подставляем в формулу разгона из покоя, выражаем ускорение.",
            ],
            steps: [
              { t: "Формула разгона из покоя",
                p: ["Общая формула координаты при разгоне:",
                    "f: x = x_0 + v_0 · t + (a · t^2)/(2)",
                    "Читается так: где стало = где было + сдвиг от начальной скорости + сдвиг от ускорения.",
                    "Так как v_0 = 0, среднее слагаемое пропадает:",
                    "f: x = x_0 + (a · t^2)/(2)"] },
              { t: "Стартовая координата",
                p: [`Строка t = 0 говорит: x_0 = ${fmtNum(x0)}.`,
                    x0 === 0 ? "Тут тело стартовало из нуля — повезло, вычитать нечего."
                             : "Тело стартовало не из нуля, и это важно: дальше это число надо будет вычесть."] },
              { t: "Берём удобную строку",
                p: [`Возьмём t = ${fmtNum(use[0])}, x = ${fmtNum(use[1])}.`,
                    `f: x − x_0 = ${fmtNum(use[1])} − ${fmtNum(x0)} = ${fmtNum(dx)}`,
                    `Тело сдвинулось на ${plural(dx, "метр", "метра", "метров")}.`] },
              { t: "Выражаем ускорение",
                p: ["Из равенства x − x_0 = (a · t²)/2 умножаем обе части на 2 и делим на t²:",
                    "f: a = (2 · (x − x_0))/(t^2)"] },
              { t: "Подставляем",
                p: [`f: a = (2 · ${fmtNum(dx)})/(${fmtNum(use[0])}^2)`,
                    `f: ${fmtNum(use[0])}^2 = ${fmtNum(use[0] * use[0])}`,
                    `f: a = (${fmtNum(2 * dx)})/(${fmtNum(use[0] * use[0])}) = ${fmtNum(a)}`] },
              { t: "Проверяем по другой строке",
                p: [`При t = ${fmtNum(rows[1][0])} формула даёт x = ${fmtNum(x0)} + (${fmtNum(a)} · ${fmtNum(rows[1][0] * rows[1][0])})/(2) = ${fmtNum(rows[1][1])}.`,
                    `В таблице ровно ${fmtNum(rows[1][1])} — значит, ускорение найдено верно.`] },
            ],
            ans: `${fmtNum(a)} (${pluralWord(a, "метр", "метра", "метров")} на секунду в квадрате)`,
            err: x0 === 0
              ? `Делят на t вместо t²: ${fmtNum(2 * dx)} / ${fmtNum(use[0])} = ${fmtNum(2 * dx / use[0])}. В формуле стоит квадрат времени.`
              : `Забывают вычесть стартовые ${fmtNum(x0)} м и считают a = 2 · ${fmtNum(use[1])} / ${fmtNum(use[0] * use[0])} = ${fmtNum(2 * use[1] / (use[0] * use[0]))}. В формуле участвует сдвиг, а не сама координата.`,
          },
          dbg: { vars: { a, x0, rows, use, dx } },
        };
      },
    },

    {
      id: "from_parabola",
      title: "Ускорение из параболы",
      check: t => {
        const v = t.dbg.vars;
        const a = 2 * v.xAt / (v.tAt * v.tAt);
        const want = v.askV ? a * v.tAsk : a;
        return Math.abs(want - toNum(t.answer)) < 1e-9 ? null : `по точке (${v.tAt}, ${v.xAt}) ускорение ${a}, ответ должен быть ${want}, а стоит ${t.answer}`;
      },
      make(rnd) {
        /* x = a·t²/2 из начала координат. Подбираем a и сетку так,
           чтобы узловые точки параболы попадали на пересечения клеток. */
        const a = rnd.pick([1, 2, 4]);
        const T = rnd.pick([3, 4]);
        const yStep = a === 1 ? 1 : a === 2 ? 2 : 4;       /* x(1) = a/2 — пусть это будет пол-клетки или клетка */
        const xAt = a * T * T / 2;
        const tAt = rnd.int(2, T);
        const xTAt = a * tAt * tAt / 2;
        const askV = rnd.chance(0.5);
        const tAsk = askV ? rnd.int(2, T + 1) : null;
        const vAsk = askV ? a * tAsk : null;
        if (!nice(xTAt) || !nice(xAt)) return GEN.kinds[1].make(rnd);

        /* гладкая линия: много точек, кружки только на целых секундах */
        const curve = [];
        for (let i = 0; i <= T * 8; i++) { const tt = i / 8; curve.push([tt, a * tt * tt / 2]); }
        const marks = [];
        for (let tt = 0; tt <= T; tt++) { const x = a * tt * tt / 2; if (Math.abs(x / yStep - Math.round(x / yStep)) < 1e-9) marks.push([tt, x]); }
        const yTo = Math.ceil((a * T * T / 2) / yStep) * yStep + yStep;
        const graph = {
          x: { label: "t, с", from: 0, to: T + (askV && tAsk > T ? 1 : 0), step: 1, tick: 1 },
          y: { label: "x, м", from: 0, to: yTo, step: yStep, tick: yStep },
          lines: [{ pts: curve, dots: false, curve: true }],
          marks,
        };
        const base = `Небольшое тело начинает равноускоренно двигаться вдоль оси Ox без начальной скорости. На рисунке приведён график зависимости координаты x этого тела от времени t.`;
        return {
          plain: askV
            ? `${base} Чему равна проекция скорости v_x этого тела в момент времени t = ${fmtNum(tAsk)} с? Ответ выразите в метрах в секунду.`
            : `${base} Определите проекцию a_x ускорения этого тела. Ответ дайте в метрах на секунду в квадрате.`,
          svg: GRAPH.plot(graph), table: null,
          answer: fmtAns(askV ? vAsk : a), unit: askV ? "м/с" : "м/с²",
          simple: askV
            ? "График изогнут — это парабола, значит, тело разгоняется. Из любой удобной точки достаёшь ускорение, а потом считаешь скорость."
            : "График изогнут — это парабола, значит, тело разгоняется. Достаточно одной удобной точки, чтобы найти ускорение.",
          raz: {
            dano: [
              "График координаты x от времени t, но линия не прямая, а изогнутая — парабола. Изогнутая линия значит: движение с разгоном.",
              "По условию тело стартует без начальной скорости: v_0 = 0. По графику видно, что стартовая координата тоже нулевая: x_0 = 0.",
              `Берём удобную точку: на ${fmtNum(tAt)}-й секунде координата ${fmtNum(xTAt)} м.`,
              askV ? `Найти надо скорость на ${fmtNum(tAsk)}-й секунде.` : "Найти надо ускорение a_x в м/с².",
            ],
            plan: askV
              ? ["По удобной точке графика находим ускорение.",
                 "Подставляем ускорение в формулу скорости.",
                 `Считаем скорость на ${fmtNum(tAsk)}-й секунде.`]
              : ["Убеждаемся: старт из нуля и без начальной скорости.",
                 "Упрощаем формулу координаты.",
                 "Подставляем одну точку графика."],
            steps: [
              { t: "Как читать параболу",
                p: ["Парабола начинается в начале координат и выходит оттуда горизонтально. Это значит: тело стартовало из точки x = 0 и стояло, то есть v_0 = 0.",
                    "Скорость видна по наклону линии: в начале он нулевой, дальше линия становится всё круче — тело разгоняется."] },
              { t: "Упрощаем формулу",
                p: ["f: x = x_0 + v_0 · t + (a · t^2)/(2)",
                    "Оба первых слагаемых нулевые, остаётся:",
                    "f: x = (a · t^2)/(2)"] },
              { t: "Выражаем и считаем ускорение",
                p: ["Умножаем обе части на 2 и делим на t²:",
                    "f: a = (2 · x)/(t^2)",
                    `Берём точку t = ${fmtNum(tAt)}, x = ${fmtNum(xTAt)}:`,
                    `f: a = (2 · ${fmtNum(xTAt)})/(${fmtNum(tAt)}^2) = (${fmtNum(2 * xTAt)})/(${fmtNum(tAt * tAt)}) = ${fmtNum(a)}`] },
              ...(askV ? [{ t: "Находим скорость",
                p: ["f: v = v_0 + a · t",
                    "Так как v_0 = 0, остаётся v = a · t.",
                    `f: v = ${fmtNum(a)} · ${fmtNum(tAsk)} = ${fmtNum(vAsk)}`,
                    `На ${fmtNum(tAsk)}-й секунде скорость равна ${fmtNum(vAsk)} м/с.`] }] : []),
            ],
            ans: askV
              ? `${fmtNum(vAsk)} (${pluralWord(vAsk, "метр", "метра", "метров")} в секунду)`
              : `${fmtNum(a)} (${pluralWord(a, "метр", "метра", "метров")} на секунду в квадрате)`,
            err: askV
              ? `Снимают с графика координату на ${fmtNum(tAsk)}-й секунде и пишут её в ответ. Координата — это место, а не скорость.`
              : `Считают наклон как у прямой: ${fmtNum(xTAt)} / ${fmtNum(tAt)} = ${fmtNum(xTAt / tAt)}, и называют это ускорением. У изогнутой линии наклон меняется — работает только формула с t².`,
          },
          dbg: { graph, vars: { a, T, tAt, xAt: xTAt, askV, tAsk, vAsk, marks } },
        };
      },
    },
  ],
};

if (typeof module !== "undefined" && module.exports) module.exports = GEN;
if (typeof window !== "undefined") (window.GEN = window.GEN || {})["fiz:" + GEN.key] = GEN;
