def trig(id, eq, fn, val, angle, seria, ans, which):
    add(id,
        "Уравнение %s. Сначала вспоминаем табличный угол, потом выписываем всю серию решений, "
        "и только потом выбираем нужный корень." % eq,
        ("seria", "koren"),
        [s("При каком значении %s равен %s? Впиши табличный ответ в долях π." % (fn, val), angle, "",
           lead="Это то самое, что стоит помнить наизусть.",
           why="Без табличного значения серию не выписать."),
         s("Серия решений: %s. Подставь целые n и найди %s корень." % (seria, which), ans, "",
           why="Корней бесконечно много, поэтому спрашивают конкретный.",
           tail="перебирай n по одному, пока не попадёшь в нужный диапазон")],
        {"in": seria, "out": str(ans)},
        why="Синус, косинус и тангенс повторяются, поэтому у уравнения бесконечно много корней. "
            "Их записывают одной формулой с целым n, а потом подставляют n по очереди, пока не "
            "найдут именно тот корень, который просят.",
        ask="Смотри: %s — тригонометрическое уравнение. С чего начнёшь?" % eq)

