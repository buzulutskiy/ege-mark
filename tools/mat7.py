Q_TEXT = "Посмотри на уравнение: где именно спрятан икс?"
HINT = ("Ответ виден по записи: под корнем, в знаменателе, в показателе степени или внутри "
        "логарифма. От этого и зависит, каким действием его освобождать.")

def build():
    plan = json.load(open("lessons/plan-mat.json", encoding="utf-8")) if __import__("os").path.exists("lessons/plan-mat.json") else {}
    try:
        form = json.load(open("lessons/form-mat.json", encoding="utf-8"))
    except Exception:
        form = {}
    try:
        qx = json.load(open("lessons/q-mat.json", encoding="utf-8"))
    except Exception:
        qx = {}
    gs = groups()
    plan["7"] = {"name": "Простейшие уравнения", "total": sum(g["count"] for g in gs),
                 "groups": gs, "unsorted": 0}
    rows = [{"key": g["key"], "f": FORM[g["key"]]["f"], "title": FORM[g["key"]]["title"],
             "what": FORM[g["key"]]["what"],
             "steps": [dict(FORM[g["key"]], title=FORM[g["key"]]["title"])],
             "tasks": list(g["tasks"]), "count": g["count"]} for g in gs]
    form["7"] = {"levels": [{"level": 1, "title": "Один приём",
                             "note": "Опознал тип уравнения — знаешь, что делать.",
                             "rows": rows, "count": sum(r["count"] for r in rows)}],
                 "total": plan["7"]["total"]}
    key_of = {i: g["key"] for g in gs for i in g["tasks"] + g.get("more", [])}
    for id, v in Q.items():
        k = key_of.get(id)
        if not k: continue
        f = dict(FORM[k])
        if id in SUB_IN: f["subst"] = SUB_IN[id]
        if id in WHY:    f["why"] = WHY[id]
        out = dict(v)
        out["formulas"] = [f]; out["formula"] = dict(f)
        dk = "drob" if k == "lin" and id in ("sd999611","sd999604","sd646314","sd646295",
                                              "sd696339","sd322878","sd1041163") else k
        opts = [{"t": DATA[dk], "ok": True}] + [{"t": DATA[d]} for d in DIST[dk]]
        r = sum(ord(c) for c in id) % len(opts)
        out["choice"] = {"q": Q_TEXT, "hint": HINT,
                         "opts": opts[r:] + opts[:r] + [
                             {"t": "Не знаю — объясни, в чём тут принцип", "tell": True}],
                         "was": re.sub(r"\s*(Что будешь делать|С чего начнёшь)\?\s*$", "",
                                       ASK.get(id, "")).replace("Смотри: ", "")}
        qx[id] = out
    json.dump(plan, open("lessons/plan-mat.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    json.dump(form, open("lessons/form-mat.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    json.dump(qx, open("lessons/q-mat.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("задание 7: разборы у %d задач" % len(Q))

if __name__ == "__main__":
    build()
