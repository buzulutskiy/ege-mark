def build():
    t = json.load(open("bank/bank-mat.json", encoding="utf-8"))["tasks"]
    plan = json.load(open("lessons/plan-mat.json", encoding="utf-8"))
    form = json.load(open("lessons/form-mat.json", encoding="utf-8"))
    for n, rules in RULES.items():
        ts = [q for q in t if str(q["task"]) == n]
        by = collections.OrderedDict((k, []) for k, _, _, _ in rules)
        rest = []
        for q in ts:
            p = (q["plain"] or "").lower()
            for k, _, _, rx in rules:
                if re.search(rx, p):
                    by[k].append(q["id"]); break
            else:
                rest.append(q["id"])
        groups = []
        for k, title, why, _ in rules:
            ids = by[k]
            if not ids: continue
            groups.append({"key": k, "title": title, "summary": why,
                           "recognize": TOPIC[n][1], "tasks": ids, "count": len(ids), "part2": True})
        if rest:
            groups.append({"key": "misc", "title": "Остальные виды",
                           "summary": "Задачи, которые не легли ни в один из типов выше — разбирай "
                                      "их по официальному решению.",
                           "recognize": TOPIC[n][1], "tasks": rest, "count": len(rest), "part2": True})
        plan[n] = {"name": TOPIC[n][0], "total": sum(g["count"] for g in groups),
                   "groups": groups, "unsorted": 0, "part2": True,
                   "note": TOPIC[n][1]}
        form[n] = {"levels": [{"level": 1, "title": "Приёмы решения", "note": TOPIC[n][1],
                               "rows": [{"key": g["key"], "f": g["title"], "title": g["title"],
                                         "what": g["summary"], "tasks": g["tasks"],
                                         "count": g["count"]} for g in groups],
                               "count": sum(g["count"] for g in groups)}],
                   "total": plan[n]["total"]}
        print("задание %-3s %-32s %3d задач в %d приёмах" % (n, TOPIC[n][0][:32],
              plan[n]["total"], len(groups)))
    json.dump(plan, open("lessons/plan-mat.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    json.dump(form, open("lessons/form-mat.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)

if __name__ == "__main__":
    build()
