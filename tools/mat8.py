RULES = [
 ("log",  r"логарифм|log"),
 ("trig", r"синус|косинус|тангенс|котангенс"),
 ("kor",  r"√|корень \d+ степени|корень из"),
 ("step", r"в степени"),
 ("drob", r"[a-zx]²|\bx\b"),
 ("chis", r"."),
]

def groups():
    t = json.load(open("bank/bank-mat.json", encoding="utf-8"))["tasks"]
    ts = [q for q in t if str(q["task"]) == "8"]
    by = collections.OrderedDict((k, []) for k, _ in RULES)
    for q in ts:
        p = (q["plain"] or "").lower()
        for k, rx in RULES:
            if re.search(rx, p):
                by[k].append(q["id"]); break
    out = []
    for k, _ in RULES:
        if not by[k]: continue
        f = FORM[k]
        out.append({"key": k, "title": f["title"], "summary": f["why"], "recognize": f["what"],
                    "tasks": by[k], "count": len(by[k])})
    print("задание 8: %d задач в %d приёмах" % (sum(len(v) for v in by.values()), len(out)))
    return out

