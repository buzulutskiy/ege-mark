def principle(p):
    g, a = given(p), asked(p)
    low = p.lower()

    # сначала то, что железно видно: уравнение или график. Слова проверяем после.
    if g == "eq":
        return "eq"
    if g in ("v", "vx"):
        if a == "a": return "slope_a"
        if a == "d": return "area_d"
        if a == "s": return "area_s"
        if a == "v": return "read"
    if g in ("x", "S"):
        if a in ("v", "a"): return "slope_v"
        if a in ("s", "d"): return "read_xs"
        return "read"
    if g == "a":
        return "form"

    # картинки нет — тогда смотрим на смысл текста
    if re.search(r"на север|на юг|на запад|на восток|под углом|перпендикуляр", low):        return "pif"
    if re.search(r"относительно (берега|земли|воды|поезда|плота|вагона|автобуса|эскалатор)|"
                 r"течени|эскалатор|навстречу|по салону|в вагоне|вдогонку|обгоня", low):    return "rel"
    if a == "avg":
        return "avg"
    return "form"



