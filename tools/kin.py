def given(p):
    p = p.lower()
    # что нарисовано — определяем по подписи вертикальной оси, она в условии идёт первой
    if re.search(r"график\w*\s*(зависимост\w*\s*)?(проекци\w*\s*)?ускорени", p):      return "a"
    if re.search(r"график\w*\s*(зависимост\w*\s*)?координат|график движения\s*x", p):  return "x"
    if re.search(r"график\w*\s*(зависимост\w*\s*)?(пройденн\w*\s*)?пут[ияь]", p):     return "S"
    if re.search(r"график.*проекци\w*\s*скорост|график.*\bv\s*_?x|график.*υ\s*_?x", p): return "vx"
    if re.search(r"график.*(модул\w*\s*скорост|скорост)", p):                            return "v"
    if re.search(r"задан\w*\s*уравнени|уравнени\w*м|зависимост\w*\s*координаты.*вид|"
                 r"x\s*=\s*-?\d|x\s*\(\s*t\s*\)\s*=", p):                           return "eq"
    if re.search(r"график|рисунк", p):                                                    return "gr"
    return "txt"


def asked(p):
    p = p.lower()
    if re.search(r"ускорени", p):              return "a"
    if re.search(r"перемещени", p):            return "d"
    if re.search(r"средн\w*\s*скорост", p):    return "avg"
    if re.search(r"\bпут[ьи]\b|пройденн", p):  return "s"
    if re.search(r"скорост", p):               return "v"
    if re.search(r"координат", p):             return "x"
    return "?"


