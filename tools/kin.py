def split_subs(key, ids, byid):
    """Раскладывает по подциклам без остатка: последнее правило — «всё остальное»."""
    rules = SUBS.get(key)
    if not rules or len(ids) < 4:
        return []
    out, used = [], set()
    for title, hint, pat in rules:
        rx = re.compile(pat, re.I | re.S)
        got = [i for i in ids if i not in used and rx.search(byid[i]["plain"])]
        used.update(got)
        if got:
            out.append({"title": title, "hint": hint, "tasks": got, "count": len(got)})
    assert len(used) == len(ids), "остались нерасфасованные: %d" % (len(ids) - len(used))
    return out if len(out) > 1 else []


def main():
    bp = os.path.join(ROOT, "bank", "bank-fiz.json")
    b = [q for q in json.load(open(bp, encoding="utf-8"))["tasks"] if q.get("task") == 1]
    by = collections.defaultdict(list)
    for q in b:
        by[principle(q["plain"])].append(q["id"])

    pp = os.path.join(ROOT, "lessons", "plan-fiz.json")
    plan = json.load(open(pp, encoding="utf-8"))
    hand = next((g for g in plan["1"]["groups"] if g.get("hand")), None)

    groups = []
    for key, title, rec in CYC:
        ids = by.get(key, [])
        if not ids:
            continue
        g = {"title": title, "recognize": rec, "count": len(ids), "tasks": ids, "key": key}
        subs = split_subs(key, ids, {q["id"]: q for q in b})
        if subs:
            g["subs"] = subs
        if hand and key == "slope_v":            # сюда ложится уже написанный руками разбор
            for f in ("theory", "algorithm", "trap", "hand"):
                if f in hand: g[f] = hand[f]
            g["title"] = hand["title"]; g["recognize"] = hand["recognize"]
        groups.append(g)
    plan["1"]["groups"] = groups
    plan["1"]["total"] = len(b)
    json.dump(plan, open(pp, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    print("кинематика: %d задач → %d циклов по принципу решения\n" % (len(b), len(groups)))
    for g in groups:
        print("  %3d  %-56s%s" % (g["count"], g["title"][:56], "  ✍ разбор написан" if g.get("theory") else ""))
        print("       %s" % g["recognize"][:96])
        for sb in g.get("subs", []):
            print("         %3d  %-42s %s" % (sb["count"], sb["title"][:42], sb["hint"][:44]))


if __name__ == "__main__":
    main()
