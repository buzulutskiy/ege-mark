def build():
    bank = {q["id"] for q in json.load(open("bank/bank-fiz.json", encoding="utf-8"))["tasks"]
            if str(q["task"]) == "2"}
    used, groups, miss = set(), [], []
    for key, title, subs in G:
        sl, tasks = [], []
        for st, ids in subs:
            ok = [i for i in ids if i in bank and i not in used]
            miss += [i for i in ids if i not in bank]
            used |= set(ok)
            if ok:
                sl.append({"title": st, "tasks": ok, "count": len(ok)})
                tasks += ok
        if not tasks:
            continue
        f = FORM[key]
        g = {"key": key, "title": f["title"], "summary": f["why"],
             "recognize": f["what"], "tasks": tasks, "count": len(tasks)}
        if len(sl) > 1:
            g["subs"] = sl
        groups.append(g)
    left = sorted(bank - used)
    print("динамика: разложено %d из %d" % (len(used), len(bank)))
    if miss: print("  в списках есть чужие id:", len(miss), miss[:5])
    if left: print("  не разложено:", len(left), left[:12])
    return groups, left

