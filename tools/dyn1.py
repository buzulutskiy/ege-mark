def fr_change(id, F0, kind, times, ans):
    """как изменится трение, если менять массу или коэффициент"""
    up = "увеличить" in kind
    what = "коэффициент трения" if "коэффициент" in kind else "массу"
    add(id,
        "Сила трения была %s Н. Меняют %s в %s раза%s. Считать заново ничего не надо: трение "
        "меняется во столько же раз." % (F0, what, times, " в большую сторону" if up else ""),
        ("ftr", "mu", "N", "mg"),
        [s("Трение равно μ · m · g. %s %s в %s раза — во сколько раз изменится трение?"
           % ("Увеличили" if up else "Уменьшили", what, times), times, "раза",
           lead="Смотри на формулу: и масса, и коэффициент стоят в ней множителями.",
           why="Если множитель вырос втрое, всё произведение вырастет втрое."),
         s("Посчитай новое трение: %s %s %s." % (F0, "·" if up else "/", times), ans, "Н",
           tail="если бы меняли скорость или площадь, трение не изменилось бы вовсе")],
        {"in": "F = %s %s %s" % (F0, "·" if up else "/", times), "out": "%s Н" % ans},
        why="Здесь не спрашивают, чему трение равно — оно уже дано, %s Н. Спрашивают, что с ним "
            "станет, если %s в %s раза. В формуле трения %s стоит простым множителем, поэтому "
            "трение изменится ровно во столько же раз: %s Н." % (
                F0, kind, times, what, ans),
        ask="Смотри: сила трения была %s Н, и %s %s в %s раза. Спрашивают новую силу трения. "
            "Что будешь делать?" % (F0, "увеличивают" if up else "уменьшают", what, times))

