Q, WHY, ASK, SUB_IN = {}, {}, {}, {}

def add(id, simple, tkeys, steps, subst=None, why=None, ask=None):
    Q[id] = {"simple": simple, "terms": terms(*tkeys), "steps": steps}
    if subst: SUB_IN[id] = subst
    if why: WHY[id] = why
    if ask: ASK[id] = ask

def s(q, a, unit="", lead="", why="", tail=""):
    d = {"q": q, "a": a}
    for k, v in (("unit", unit), ("lead", lead), ("why", why), ("tail", tail)):
        if v: d[k] = v
    return d

