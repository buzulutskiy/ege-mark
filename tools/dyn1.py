        "больше него трение вырасти не может. Если тянут слабее предела, тело стоит, и трение равно "
        "той силе, которой тянут." % F,
        ("pok", "ftr", "mu", "N", "mg"),
        [s("Найди предельное трение: μ · m · g = %s · %s · 10." % (mu, m), Fmax, "Н",
           lead="Это максимум, на который трение вообще способно.",
           why="Больше этого значения трение стать не может — тело поедет."),
         s("Тянут с силой %s Н. Что меньше — эта сила или предел? Впиши силу трения." % F, ans, "Н",
           why="Пока тянут слабее предела, тело стоит и трение равно силе тяги. Как только сила "
               "превысит предел, тело поедет, и трение станет равным пределу.",
           tail=note or "трение покоя подстраивается под ту силу, которой тянут")],
