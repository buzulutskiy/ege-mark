DIST = {"arch": ["float","phyd"], "float": ["arch","phyd"], "phyd": ["arch","psolid"],
        "psolid": ["phyd","arch"], "ucomm": ["phyd","float"], "press": ["psolid","phyd"]}

def build():
    plan = json.load(open("lessons/plan-fiz.json", encoding="utf-8"))
    form = json.load(open("lessons/form-fiz.json", encoding="utf-8"))
    qx = json.load(open("lessons/q-fiz.json", encoding="utf-8"))
    gs = groups()
    plan["4"] = {"name": "Гидростатика", "total": sum(g["count"] for g in gs),
                 "groups": gs, "unsorted": 0}
    rows = [{"key": g["key"], "f": FORM[g["key"]]["f"], "title": FORM[g["key"]]["title"],
             "what": FORM[g["key"]]["what"],
             "steps": [dict(FORM[g["key"]], title=FORM[g["key"]]["title"])],
             "tasks": list(g["tasks"]), "count": g["count"]} for g in gs]
    form["4"] = {"levels": [{"level": 1, "title": "Одна формула",
                             "note": "Подставил числа — получил ответ.",
                             "rows": rows, "count": sum(r["count"] for r in rows)}],
                 "total": plan["4"]["total"]}
    key_of = {i: g["key"] for g in gs for i in g["tasks"] + g.get("more", [])}
    n = 0
    for id, v in Q.items():
        k = key_of.get(id)
        if not k: continue
        f = dict(FORM[k])
        if id in SUB_IN: f["subst"] = SUB_IN[id]
        if id in WHY:    f["why"] = WHY[id]
        opts = [{"t": ACT[k], "ok": True}] + [{"t": ACT[d]} for d in DIST[k]]
        r = sum(ord(c) for c in id) % len(opts)
        out = dict(v)
        out["formulas"] = [f]; out["formula"] = dict(f)
        out["choice"] = {"q": ASK.get(id, "Что тут надо сделать?"),
                         "opts": opts[r:] + opts[:r] + [
                             {"t": "Не знаю — объясни, в чём тут принцип", "tell": True}],
                         "hint": "Посмотри, что дано и что спрашивают — формулу выбирают по ним."}
        qx[id] = out; n += 1
    json.dump(plan, open("lessons/plan-fiz.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    json.dump(form, open("lessons/form-fiz.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    json.dump(qx, open("lessons/q-fiz.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("гидростатика: разборы у %d задач" % n)

if __name__ == "__main__":
    build()
