Q_TEXT = "Перечитай условие: что в нём уже дано и что просят найти?"
HINT = ("Ответ есть прямо в тексте задачи. Посмотри, какие величины названы с числами — "
        "это и есть «дано». А что спрашивают, выделено жирным.")

def apply():
    plan = json.load(open("lessons/plan-fiz.json", encoding="utf-8"))
    qx = json.load(open("lessons/q-fiz.json", encoding="utf-8"))
    import sys, os
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import kin1, dyn, gidro
    by_f = {}                                  # формула → ключ раздела
    for src in (kin1.FORM, dyn.FORM, gidro.FORM):
        for k, f in src.items():
            by_f.setdefault(f["f"], k)
    key_of = {}
    for n, d in plan.items():
        for g in d.get("groups", []):
            for i in g.get("tasks", []) + g.get("more", []):
                key_of[i] = g.get("key")
    n = 0
    for id, v in qx.items():
        k = key_of.get(id)
        if k not in DATA:                       # у кинематики свои имена циклов — идём от формулы
            f = (v.get("formula") or {}).get("f")
            k = by_f.get(f, k)
        if k not in DATA:
            continue
        opts = [{"t": DATA[k], "ok": True}] + [{"t": DATA[d]} for d in DIST.get(k, []) if d in DATA]
        r = sum(ord(c) for c in id) % len(opts)
        old = v.get("choice") or {}
        v["choice"] = {
            "q": Q_TEXT,
            "opts": opts[r:] + opts[:r] + [{"t": "Не знаю — объясни, в чём тут принцип", "tell": True}],
            "hint": HINT,
            "was": re.sub(r"\s*(Что будешь делать|С чего начнёшь)\?\s*$", "",
                          old.get("q", "")).replace("Смотри: ", ""),          # прежний вопрос-подводка пригодится вторым шагом
        }
        n += 1
    json.dump(qx, open("lessons/q-fiz.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("шаг «что дано» проставлен: %d задач" % n)

if __name__ == "__main__":
    apply()
