def many_v(id, sub, simple, rows, ask, ans):
    """несколько прямых кусков: посчитать скорость на каждом и выбрать нужный"""
    st = []
    for i, (t, dx, dt, v) in enumerate(rows):
        st.append(s("Участок %s: координата изменилась на %s м за %s с. Чему равна скорость?" % (t, dx, dt), v, "м/с",
          lead=("График состоит из нескольких прямых кусков — считаем скорость на каждом по очереди." if i == 0 else "")))
    st.append(s(ask, ans, "м/с", why="Сравниваем именно модули — то есть числа без минусов.",
      tail="знак при выборе не смотрим, а вот в ответ его писать не надо"))
    add(id, "slope_v", sub, 3, simple, ("gr_x","vx","nakl","mod"), st)

