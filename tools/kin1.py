def expr(q, a):
    """из моего же вопроса вида «…: (10 × 4) ÷ 2?» достаём саму арифметику"""
    if ":" not in q: return mns(a)
    e = q.split(":")[-1].strip(" ?").replace(" ÷ ", "/").replace(" × ", "·")
    e = re.sub(r"\s*(м/с²|м/с|км/ч|см/с|м|с)(?=[\s·)+×÷]|$)", "", e)   # единицы в подстановке лишние
    return re.sub(r"\s{2,}", " ", e).strip()

def s(q, a, unit="", lead="", why="", tail=""):
    d = {"q": q, "a": a}
    if unit: d["unit"] = unit
    if lead: d["lead"] = lead
    if why:  d["why"] = why
    if tail: d["tail"] = tail
    return d

