# ══════════ 3. Ускорение по наклону графика скорости ══════════
def slope_a(id, who, t1, t2, v1, v2, dv, dt, ans, note=""):
    grow = "выросла" if float(str(dv).replace(",", ".")) > 0 else "упала"
    simple = ("На графике скорости бери кусок с %s по %s. Скорость там %s с %s м/с до %s м/с. "
              "Ускорение — это насколько быстро она менялась: изменение скорости делить на время. %s") % (
              t1, t2, grow, v1, v2, note)
    add(id, "slope_a", "Обычный участок", 2, simple.strip(), ("gr_v","vx","ax","nakl"),
     [s("Чему равна скорость %s в момент %s?" % (actor(id) or who, t1), v1, "м/с",
        lead="Снимаем с графика два числа — скорость в начале куска и в конце."),
      s("А в момент %s?" % t2, v2, "м/с"),
      s("На сколько изменилась скорость? Из второй вычти первую.", dv, "м/с",
        why="Ускорение всегда считается через изменение скорости, а не через саму скорость."),
      s("Сколько секунд прошло?", dt, "с"),
      s("Раздели изменение скорости на время — чему равна проекция ускорения?", ans, "м/с²",
        why="Это наклон графика скорости: «вверх» делить на «вбок».",
        tail="минус значит, что тело тормозит или разгоняется против оси" if str(ans).startswith("-") else "")],
     {"in": "a = (%s − %s)/(%s − %s)" % (mns(v2), mns(v1), num(t2), num(t1)),
      "out": mns(ans) + " м/с²"},
     ask=("Смотри: сбоку на графике отмечена скорость%s, а спрашивают ускорение "
          "на куске с %s по %s. Что будешь делать?" % (of(id), t1, t2)),
     why=("Сбоку на графике — скорость, а спрашивают ускорение на куске с %s по %s. "
          "Ускорение показывает, насколько быстро менялась скорость. Значит, смотрим, "
          "как она изменилась (с %s до %s м/с), и делим на прошедшее время." % (t1, t2, mns(v1), mns(v2))))

