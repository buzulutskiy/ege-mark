def slope_v(id, sub, diff, simple, who, x1, x2, t1, t2, dx, dt, ans, unit="м/с", tk=("gr_x","vx","nakl"), extra=None):
    """три шага: снять две точки, найти разности, поделить"""
    st = [
     s("Какая координата у %s в момент %s?" % (actor(id) or who, t1), x1, "м",
       lead="Найди на графике две точки — начало и конец нужного куска."),
     s("А какая координата в момент %s?" % t2, x2, "м"),
     s("На сколько изменилась координата? Из второй вычти первую.", dx, "м",
       why="Скорость показывает, сколько метров набежало за секунду, поэтому сначала считаем, сколько всего набежало."),
     s("Сколько секунд прошло между этими моментами?", dt, "с"),
     s("Раздели изменение координаты на время — чему равна проекция скорости?", ans, unit,
       why="Это и есть наклон графика: «вверх» делить на «вбок».",
       tail="минус означает, что тело едет против оси" if str(ans).startswith("-") else ""),
    ]
    if extra: st += extra
    add(id, "slope_v", sub, diff, simple, tk, st,
        {"in": "v = (%s − %s)/(%s − %s)" % (mns(x2), mns(x1), num(t2), num(t1)),
         "out": mns(ans) + " " + unit},
        ask=("Смотри: на графике снизу время, а сбоку — где находится%s. "
             "А спрашивают скорость на куске с %s по %s. С чего начнёшь?" % (of2(id), t1, t2)),
        why=("Сбоку на графике — где тело было, а спрашивают скорость на куске с %s по %s. "
             "За этот кусок координата сменилась с %s на %s м, то есть на %s м, и заняло это "
             "%s секунд. Скорость и есть «метры за секунду», поэтому одно делят на другое." % (
                 t1, t2, mns(x1), mns(x2), mns(dx), dt)))

